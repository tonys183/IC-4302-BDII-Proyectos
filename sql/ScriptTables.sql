CREATE TABLE Client (
    client_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR2(50),
    last_name1 VARCHAR2(50),
    last_name2 VARCHAR2(50),
    phone_number VARCHAR2(20),
    email VARCHAR2(100)
);

CREATE TABLE Status (
    status_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status_name VARCHAR2(50)
);

CREATE TABLE CustomerOrder (
    order_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_date DATE,
    total_price NUMBER(10,2),
    client_id NUMBER,
    status_id NUMBER,
    FOREIGN KEY (client_id) REFERENCES Client(client_id),
    FOREIGN KEY (status_id) REFERENCES Status(status_id)
);

CREATE TABLE Supply (
    supply_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supply_name VARCHAR2(100),
    stock NUMBER
);

CREATE TABLE OrderDetail (
    order_id NUMBER,
    supply_id NUMBER,
    book_id NUMBER,
    service_id NUMBER,
    date_detail DATE,
    quantity NUMBER,
    unit_price NUMBER(10,2),
    total_detail NUMBER(10,2),
    PRIMARY KEY (order_id, supply_id, book_id, service_id),
    FOREIGN KEY (order_id) REFERENCES CustomerOrder(order_id),
    FOREIGN KEY (supply_id) REFERENCES Supply(supply_id),
    FOREIGN KEY (book_id) REFERENCES Book(book_id),
    FOREIGN KEY (service_id) REFERENCES Service(service_id)
);

CREATE TABLE ServiceType (
    type_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_name VARCHAR2(50)
);

CREATE TABLE Service (
    service_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_name VARCHAR2(100),
    type_id NUMBER,
    FOREIGN KEY (type_id) REFERENCES ServiceType(type_id)
);

CREATE TABLE Genre (
    genre_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genre_name VARCHAR2(100)
);

CREATE TABLE Publisher (
    publisher_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    publisher_name VARCHAR2(100)
);

CREATE TABLE Author (
    author_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_name VARCHAR2(100)
);

CREATE TABLE Book (
    book_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_name VARCHAR2(200),
    ISBN VARCHAR2(20) UNIQUE,
    publisher_id NUMBER,
    FOREIGN KEY (publisher_id) REFERENCES Publisher(publisher_id)
);

CREATE TABLE Book_Author (
    book_id NUMBER,
    author_id NUMBER,
    PRIMARY KEY (book_id, author_id),
    FOREIGN KEY (book_id) REFERENCES Book(book_id),
    FOREIGN KEY (author_id) REFERENCES Author(author_id)
);

CREATE TABLE Genre_Book (
    genre_id NUMBER,
    book_id NUMBER,
    PRIMARY KEY (genre_id, book_id),
    FOREIGN KEY (genre_id) REFERENCES Genre(genre_id),
    FOREIGN KEY (book_id) REFERENCES Book(book_id)
);

CREATE TABLE Library_User (
   user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   username VARCHAR2(50) UNIQUE,
   password VARCHAR2(255)
);

CREATE TABLE Log_Table (
    log_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER,
    action VARCHAR2(100),
    action_date DATE,
    current_value NUMBER,
    previous_value NUMBER,
    FOREIGN KEY (user_id) REFERENCES Library_User(user_id)
);